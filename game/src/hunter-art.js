import { rect, texture } from './pixel-utils.js';

// Paint the approved 32x34 sprites once. No extra work is added to the frame loop.
function createPainter(ctx){
  const r=(x,y,w,h,color)=>rect(ctx,x,y,w,h,color);
  const p=(points,color)=>{
    const minX=Math.floor(Math.min(...points.map(v=>v[0]))),maxX=Math.ceil(Math.max(...points.map(v=>v[0])));
    const minY=Math.floor(Math.min(...points.map(v=>v[1]))),maxY=Math.ceil(Math.max(...points.map(v=>v[1])));
    for(let y=minY;y<maxY;y++)for(let x=minX;x<maxX;x++){
      let inside=false;for(let i=0,j=points.length-1;i<points.length;j=i++){
        const [xi,yi]=points[i],[xj,yj]=points[j];
        if((yi>y+.5)!=(yj>y+.5)&&x+.5<(xj-xi)*(y+.5-yi)/(yj-yi)+xi)inside=!inside;
      }
      if(inside)r(x,y,1,1,color);
    }
  };
  const shadow=()=>{r(7,29,18,2,'#13251f65');r(10,31,12,1,'#13251f35');};
  return {r,p,shadow};
}

