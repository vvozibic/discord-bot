const cache = new Map();
export function createHunterArt(theme = 'forest') {
  const id = theme === 'industrial' ? 'iron-reaver' : 'crimson-tracker';
  if (!cache.has(id)) cache.set(id, { id, texture:texture(32, 34, id === 'iron-reaver' ? paintIronReaver : paintCrimsonTracker) });
  return cache.get(id);
}
